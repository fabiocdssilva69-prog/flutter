def validate_profiles():
    """Valida se todos os profiles estão corretos"""
    db = firestore.client()
    profiles_ref = db.collection('profiles')
    
    print("\n🔍 Validando profiles...\n")
    
    docs = profiles_ref.get()
    issues = []
    
    for doc in docs:
        doc_id = doc.id
        data = doc.to_dict()
        
        # Validações
        if data.get('accountType') not in ['barber', 'barbershop']:
            issues.append(f"{doc_id}: accountType inválido ({data.get('accountType')})")
        
        if not isinstance(data.get('createdAt'), int):
            issues.append(f"{doc_id}: createdAt não é number")
        
        if not isinstance(data.get('updatedAt'), int):
            issues.append(f"{doc_id}: updatedAt não é number")
        
        if 'boostedUntil' not in data:
            issues.append(f"{doc_id}: boostedUntil faltando")
        elif data['boostedUntil'] is not None and not isinstance(data['boostedUntil'], int):
            issues.append(f"{doc_id}: boostedUntil não é null/number")
        
        if not isinstance(data.get('isPremium'), bool):
            issues.append(f"{doc_id}: isPremium não é boolean")
        
        if not data.get('email'):
            issues.append(f"{doc_id}: email faltando")
    
    if not issues:
        print("✅ TODOS OS PROFILES ESTÃO VÁLIDOS!\n")
        return True
    else:
        print("❌ ISSUES ENCONTRADOS:\n")
        for issue in issues:
            print(f"   - {issue}")
        print()
        return False

